"""Independent replay: all (a,u) divisor pairs, not TS's single-residue u shortcut.

Old retained survivors are regenerated by complete B^2 gates in the earlier
stdlib verifier. No TypeScript outputs are read. No disk files are written.
"""
import argparse
import hashlib
import json
from math import gcd, isqrt, lcm
from pathlib import Path
import runpy

prior = runpy.run_path(str(Path(__file__).with_name("verify-adaptive-corridor.py")))
factors, divisors = prior["factors"], prior["divisors"]
full_gate_closed = prior["full_gate_closed"]


def inverse_search(n, max_s=4095, prime_only=False):
    for s in range(3, max_s + 1, 4):
        if prime_only and any(s % q == 0 for q in range(2, isqrt(s) + 1)):
            continue
        m = (s + 1) // 4
        # Exhaust all factor pairs; deliberately do not derive u from (-an)%s.
        for a in divisors(factors(m)):
            for u in divisors(factors(m // a)):
                if gcd(a, u) != 1 or (a * n + u) % s:
                    continue
                v, k = (a * n + u) // s, m // (a * u)
                assert (u + v) % a == 0
                shift = (u + v) // a
                assert shift % 4 == 3 and n + shift == 4 * u * v * k
                x, y, z = sorted([u * v * k, a * n * u * k, a * n * v * k])
                if not x < y < z:
                    continue
                assert 4 * x * y * z == n * (x * y + x * z + y * z)
                assert sum(d % n == 0 for d in (x, y, z)) == 2
                return {"s": s, "construction": {"a": a, "u": u, "s": s, "v": v, "k": k, "shift": shift},
                        "witness": {"n": str(n), "x": str(x), "y": str(y), "z": str(z)}}
    return {"s": None, "construction": None, "witness": None}


def structural_replay():
    # Exhaustive small symbolic domain: candidate pairs cannot retarget a divisor
    # of n+1 unless the normalized pair is (1,1), including composite s.
    unit_cases = separation_cases = 0
    for s in range(3, 256, 4):
        m = (s + 1) // 4
        pairs = [(a, u) for a in divisors(factors(m)) for u in divisors(factors(m // a)) if gcd(a, u) == 1]
        for a, u in pairs:
            if (u - a) % s == 0:
                assert (a, u) == (1, 1)
            unit_cases += 1
        for a0 in range(1, 9):
            for u0 in range(1, 9):
                if gcd(a0, u0) != 1 or s <= 8 * max(a0, u0):
                    continue
                for a in range(1, 9):
                    for u in range(1, 9):
                        if gcd(a, u) != 1:
                            continue
                        if (a0 * u - a * u0) % s == 0:
                            assert (a, u) == (a0, u0)
                        separation_cases += 1
    # Non-vacuous control: modulus too small allows two different normalized ratios.
    assert (1 * 4 - 1 * 1) % 3 == 0
    # Prime-only restriction cannot synthesize this particular composite witness.
    assert factors(143) == {11: 1, 13: 1} and 143 % 144 == 143
    assert all(q % 144 != 143 for q in (11, 13))
    atlases = []
    for q in (7, 11, 19, 23, 127):
        m = (q + 1) // 4
        squares = {r * r % q for r in range(1, q)}
        # Modular inverse computed by Python pow, unlike the TypeScript loop.
        pairs = [(a, u, -u * pow(a, -1, q) % q) for a in divisors(factors(m))
                 for u in divisors(factors(m // a)) if gcd(a, u) == 1]
        residues = {r for _, _, r in pairs}
        assert residues.isdisjoint(squares)
        atlases.append({"q": q, "pairCount": len(pairs), "usableResidues": sorted(residues),
                        "missedNonresidues": sorted(set(range(1, q)) - squares - residues)})
    spacing = lcm(840, *range(3, 20, 4))
    assert spacing == 175560 and prior["prime"](351121) and 351121 == 2 * spacing + 1
    assert inverse_search(351121, 19)["s"] is None
    return {"unitRetargetPairs": unit_cases, "separationComparisons": separation_cases,
            "primeAtlases": atlases, "fixedDivisorProgressionControl": {"n": 351121, "maxS": 19, "spacing": str(spacing)},
            "writtenLemmasNotLeanFormalized": True}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--limit", type=int, default=1_000_000)
    args = parser.parse_args()
    if not 841 <= args.limit <= 200_000_000:
        parser.error("limit must be within 841..200000000")
    sieve = bytearray(b"\x01") * (args.limit // 2 + 1)
    sieve[0] = 0
    for q in range(3, isqrt(args.limit) + 1, 2):
        if sieve[q // 2]:
            start = q * q // 2
            sieve[start::q] = b"\x00" * ((len(sieve) - 1 - start) // q + 1)
    digest = hashlib.sha256()
    counts, examples = {}, {}
    prime_count = survivors = largest_s = largest_parameter = 0
    for n in range(841, args.limit + 1, 840):
        if not sieve[n // 2]:
            continue
        prime_count += 1
        if any(q % 3 != 1 for q in factors((n + 3) // 4)) or any(q % 7 not in {1, 2, 4} for q in factors((n + 7) // 4)):
            continue
        if not all(full_gate_closed(n, a) for a in (11, 15, 19)):
            continue
        survivors += 1
        full, prime = inverse_search(n), inverse_search(n, prime_only=True)
        category = ("S_INTERVAL_MISS" if full["s"] is None else "COMPOSITE_REQUIRED_IN_INTERVAL"
                    if prime["s"] is None else "PRIME_ALSO_FOUND")
        counts[category] = counts.get(category, 0) + 1
        examples.setdefault(category, {"n": n, "full": full, "prime": prime})
        largest_s = max(largest_s, full["s"] or 0)
        if full["construction"]:
            largest_parameter = max(largest_parameter, full["construction"]["a"], full["construction"]["u"])
        row = {"n": n, "category": category, "firstS": full["s"], "primeFirstS": prime["s"],
               "construction": full["construction"], "witness": full["witness"]}
        digest.update(json.dumps(row, separators=(",", ":")).encode())
    controls = [{"n": n, "all": inverse_search(n), "prime": inverse_search(n, prime_only=True)}
                for n in (2521, 131041, 4037881, 10051441, 171348241, 131433121, 17907121)]
    assert inverse_search(131433121, 142)["s"] is None
    assert inverse_search(131433121, 143)["construction"]["u"] == 9
    print(json.dumps({"limit": args.limit, "maxS": 4095, "primeCount": prime_count, "survivors": survivors,
        "counts": counts, "largestFirstS": largest_s, "largestParameter": largest_parameter,
        "examples": examples, "controls": controls, "structuralReplay": structural_replay(),
        "manifestDigest": digest.hexdigest(),
        "scope": "Finite complete factor-pair replay at maxS=4095. No universal escape or primality infinitude theorem."}, indent=2))


if __name__ == "__main__":
    main()
