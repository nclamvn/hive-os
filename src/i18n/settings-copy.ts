export function settingsValueLabel(locale: Locale, value: string): string {
  if (locale === "vi" && viValues[value]) return viValues[value];
  return value
    .toLowerCase()
    .replaceAll("_", " ")
    .replace(/(^|\s)\S/g, (letter) => letter.toUpperCase());
}
